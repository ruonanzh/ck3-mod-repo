/**
 * mod-semantics - the name-level semantic checks of validate_mod for a CK3 mod.
 *
 * It answers two questions that a brace and quote check cannot:
 *
 *   1. A new object needs its localization key. The key is derived from the object key, so a new
 *      object cannot borrow a vanilla key. The mapped kinds and their keys:
 *        - a trait in `common/traits/`: `trait_<key>` and `trait_<key>_desc`
 *          (the wiki states both: docs/wiki/Trait_modding.md, the *localization* section)
 *        - a decision in `common/decisions/`: `<key>` and `<key>_desc`
 *          (the wiki states the four keys: docs/wiki/Decisions_modding.md. This check requires the
 *          two that have no default. `_tooltip` and `_confirm` have defaults in
 *          `common/decisions/_decisions.info`, so a mod may leave them out.)
 *        - a character interaction in `common/character_interactions/`: `<key>`
 *          (the name defaults to the interaction key: `common/character_interactions/
 *          _character_interactions.info`. The wiki page has no localization section, so this check
 *          requires only the name and nothing else.)
 *      A scripted effect, an on_action, and a scripted GUI need no loc key, so they are not mapped:
 *      vanilla itself ships them with no key.
 *
 *   2. An effect, trigger, or modifier name must be a name the game knows. These names are code
 *      objects: PDXScript has no compile step, so a mod cannot add one
 *      (docs/wiki/README.md records the measurement). The game's own dumps list them all
 *      (`docs/script_docs/`). A name that is not in the dumps but is one or two characters away from
 *      a name that is gets a WARN with the closest name. A name that is far from every dumped name
 *      stays silent: it can be a vanilla object, a scripted name, or a mod-defined name, and none of
 *      those proves a mistake. The known set also holds every word that the vanilla script files use,
 *      because a field such as `random_traits` is correct and appears in no definition list. A
 *      misspelling that happens to be a vanilla field name therefore passes silently.
 *
 * Both checks are WARN only. Neither proves that a name is wrong, and neither proves that a new name
 * exists. They are not a scope or a type check.
 *
 * Degradation, because the inputs are repo setup and not repo content:
 *   - `docs/script_docs/` is committed, so it is usually present. When it is missing, check 2 is
 *     skipped with a NOTE, because the dumps are the whole basis of that check.
 *   - `game-scripts/vanilla/` is generated by sync_game_scripts and is not committed. Check 2 needs it
 *     to recognize the names that vanilla itself declares, so when it is missing, check 2 is skipped
 *     with a NOTE instead of reporting every vanilla object as unknown.
 *
 * Read only, no third-party dependency, and the output text is ASCII English.
 */
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { MIRROR_DIRNAME, MIRROR_ROOT_DIRNAME, dumpDir, mirrorDirs } from "./game-paths";

export interface SemanticFinding {
  code: string;
  /** The path of the file, relative to the mod root, POSIX separators. */
  rel: string;
  message: string;
  /** warn means fix it, note means a check was skipped and says why. */
  level: "warn" | "note";
}

export interface SemanticResult {
  checked: string[];
  findings: SemanticFinding[];
}

/** A name token: at least 8 characters, so a short field name is never a candidate. */
const TOKEN_RE = /(?<![A-Za-z0-9_.$#:])[a-z][a-z0-9_]{7,}(?![A-Za-z0-9_.])/g;
/** A name that the script introduces itself, and that is therefore not a statement about the game. */
const SAVED_NAME_RE = /\bsave_(?:temporary_)?scope(?:_value)?_as[ \t]*=[ \t]*([A-Za-z_][A-Za-z0-9_]*)/g;
/** A top-level definition: `name = {` at the start of a line. A nested field is indented. */
const TOP_DEF_RE = /^([A-Za-z_][A-Za-z0-9_.]*)[ \t]*=[ \t]*\{/;
/** An inline scripted definition: `scripted_effect name = {`. */
const INLINE_SCRIPTED_RE = /^[ \t]*scripted_(?:effect|trigger)[ \t]+([A-Za-z_][A-Za-z0-9_.]*)[ \t]*=/i;
/** A localization key line: `  key:0 "value"`. */
const LOC_KEY_RE = /^[ \t]*([A-Za-z0-9_.\-]+)[ \t]*:[ \t]*\d*[ \t]*"/;
/** The maximum number of findings that the caller prints. */
export const MAX_SEMANTIC_FINDINGS = 25;

const toPosix = (p: string): string => p.split(sep).join("/");

/**
 * The text with comments and quoted strings blanked out. A `#` inside a string is literal, so the
 * two states are tracked together, and a token that only appears in player-facing text is never a
 * candidate.
 */
function scriptOnly(text: string): string {
  let out = "";
  let inString = false;
  let inComment = false;
  for (const ch of text) {
    if (inComment) {
      if (ch === "\n") {
        inComment = false;
        out += ch;
      } else out += " ";
      continue;
    }
    if (inString) {
      if (ch === '"') {
        inString = false;
        out += ch;
      } else out += ch === "\n" ? ch : " ";
      continue;
    }
    if (ch === '"') {
      inString = true;
      out += ch;
      continue;
    }
    if (ch === "#") {
      inComment = true;
      out += " ";
      continue;
    }
    out += ch;
  }
  return out;
}

/** Every file under root whose relative path passes the filter. */
function walkFiles(root: string, keep: (rel: string) => boolean): Array<{ abs: string; rel: string }> {
  const out: Array<{ abs: string; rel: string }> = [];
  const walk = (dir: string): void => {
    let entries;
    try {
      entries = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      if (entry.name === ".git") continue;
      const abs = join(dir, entry.name);
      const rel = toPosix(relative(root, abs));
      if (entry.isDirectory()) walk(abs);
      else if (entry.isFile() && keep(rel)) out.push({ abs, rel });
    }
  };
  walk(root);
  return out;
}

/** The top-level definitions of one file, each with the text of its block body. */
function definitionBodies(text: string): Array<{ id: string; body: string }> {
  const out: Array<{ id: string; body: string }> = [];
  const clean = scriptOnly(text);
  let offset = 0;
  for (const line of clean.split("\n")) {
    const top = TOP_DEF_RE.exec(line);
    const brace = top ? line.indexOf("{") : -1;
    if (top && brace >= 0) {
      const start = offset + brace;
      let depth = 0;
      let end = start;
      for (let i = start; i < clean.length; i += 1) {
        if (clean[i] === "{") depth += 1;
        else if (clean[i] === "}") {
          depth -= 1;
          if (depth === 0) {
            end = i;
            break;
          }
        }
      }
      out.push({ id: top[1], body: clean.slice(start, end + 1) });
    }
    offset += line.length + 1;
  }
  return out;
}

/** Whether a block declares a field of its own. */
function hasOwnField(body: string, field: string): boolean {
  return new RegExp(`(?:^|\\n)[ \\t]*${field}[ \\t]*=`, "i").test(body);
}

/** The top-level definition names in one script file, including an inline scripted declaration. */
function definitionsIn(text: string, into: Set<string>): void {
  for (const line of scriptOnly(text).split(/\r?\n/)) {
    const inline = INLINE_SCRIPTED_RE.exec(line);
    if (inline) {
      into.add(inline[1]);
      continue;
    }
    const top = TOP_DEF_RE.exec(line);
    if (top) into.add(top[1]);
  }
}

/** The keys that a mod declares in its localization files. */
function modLocKeys(modDir: string): Set<string> {
  const keys = new Set<string>();
  const files = walkFiles(modDir, (rel) => /(^|\/)localization\/.*\.yml$/i.test(rel));
  for (const file of files) {
    let text = "";
    try {
      text = readFileSync(file.abs, "utf8");
    } catch {
      continue;
    }
    for (const line of text.split(/\r?\n/)) {
      const m = LOC_KEY_RE.exec(line);
      if (m) keys.add(m[1]);
    }
  }
  return keys;
}

/**
 * The derived localization keys of a new object, by data directory. A directory that this table does
 * not name needs no loc key, or needs one that this tool cannot derive.
 *
 * A kind can declare its own `desc` field. When it does, the derived `_desc` key is not needed, and
 * requiring it would report a correct mod. The observed form is `desc = <another key>` for a
 * decision, and `desc = { first_valid = { triggered_desc = { desc = <key> } } }` for a trait.
 */
const LOC_REQUIREMENTS: Array<{
  dir: string;
  kind: string;
  required: (id: string, body: string) => string[];
}> = [
  {
    dir: "common/traits",
    kind: "trait",
    required: (id, body) => {
      // The wiki: "By default, the name key is trait_<key>". A trait may set `key` itself.
      const key = /(?:^|\n)[ \t]*key[ \t]*=[ \t]*([A-Za-z_][A-Za-z0-9_.]*)/.exec(body)?.[1] ?? id;
      const nameKey = `trait_${key}`;
      return hasOwnField(body, "desc") ? [nameKey] : [nameKey, `${nameKey}_desc`];
    },
  },
  {
    dir: "common/decisions",
    kind: "decision",
    required: (id, body) => (hasOwnField(body, "desc") ? [id] : [id, `${id}_desc`]),
  },
  {
    dir: "common/character_interactions",
    kind: "character interaction",
    required: (id) => [id],
  },
];

/** The vanilla directories whose top-level names count as known. Bounded on purpose: the whole
 * mirror holds about 21000 files. */
const VANILLA_NAME_DIRS = [
  "common/scripted_effects",
  "common/scripted_triggers",
  "common/script_values",
  "common/on_action",
  "common/traits",
  "common/decisions",
  "common/character_interactions",
  "common/modifiers",
  "common/buildings",
  "common/activities",
  "common/schemes",
  "common/scripted_guis",
];

/** The engine name list: every effect, trigger, and modifier that the game declares. */
interface DumpNames {
  names: Set<string>;
  /** Names grouped by their first character, so the closest-name search stays cheap. */
  byFirstChar: Map<string, string[]>;
}

function readDumpNames(dir: string): DumpNames | null {
  const read = (name: string): string | null => {
    try {
      return readFileSync(join(dir, name), "utf8");
    } catch {
      return null;
    }
  };
  const effects = read("effects.log");
  const triggers = read("triggers.log");
  const modifiers = read("modifiers.log");
  if (!effects && !triggers) return null;
  const names = new Set<string>();
  for (const text of [effects, triggers]) {
    if (!text) continue;
    for (const line of text.split(/\r?\n/)) {
      const m = /^([A-Za-z_][A-Za-z0-9_.]*)[ \t]+-[ \t]/.exec(line);
      if (m) names.add(m[1]);
    }
  }
  if (modifiers) {
    for (const line of modifiers.split(/\r?\n/)) {
      // A templated name such as `$TRAIT_TRACK$_xp_degradation_mult` is a family, not a name.
      const m = /^Tag:[ \t]*([A-Za-z_][A-Za-z0-9_.]*)[ \t]*$/.exec(line);
      if (m) names.add(m[1]);
    }
  }
  const byFirstChar = new Map<string, string[]>();
  for (const name of names) {
    const bucket = byFirstChar.get(name[0]);
    if (bucket) bucket.push(name);
    else byFirstChar.set(name[0], [name]);
  }
  return { names, byFirstChar };
}

/** The number of single-character edits that turn a into b, or max + 1 when it is larger than max. */
function editDistance(a: string, b: string, max: number): number {
  if (Math.abs(a.length - b.length) > max) return max + 1;
  const prev = new Array<number>(b.length + 1);
  const cur = new Array<number>(b.length + 1);
  for (let j = 0; j <= b.length; j += 1) prev[j] = j;
  for (let i = 1; i <= a.length; i += 1) {
    cur[0] = i;
    let rowMin = cur[0];
    for (let j = 1; j <= b.length; j += 1) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + cost);
      if (cur[j] < rowMin) rowMin = cur[j];
    }
    if (rowMin > max) return max + 1;
    for (let j = 0; j <= b.length; j += 1) prev[j] = cur[j];
  }
  return prev[b.length];
}

/** The closest known name within max edits, or null. */
function closestName(token: string, dump: DumpNames, max: number): string | null {
  let best: string | null = null;
  let bestDistance = max + 1;
  for (const name of dump.byFirstChar.get(token[0]) ?? []) {
    const distance = editDistance(token, name, bestDistance - 1);
    if (distance < bestDistance) {
      best = name;
      bestDistance = distance;
      if (distance === 1) return best;
    }
  }
  return bestDistance <= max ? best : null;
}

/** The findings for check 1: a new object without its derived localization keys. */
function checkNewObjectLoc(modDir: string, findings: SemanticFinding[]): boolean {
  const keys = modLocKeys(modDir);
  let ran = false;
  for (const rule of LOC_REQUIREMENTS) {
    const files = walkFiles(modDir, (rel) => rel.startsWith(`${rule.dir}/`) && rel.endsWith(".txt"));
    for (const file of files) {
      let text = "";
      try {
        text = readFileSync(file.abs, "utf8");
      } catch {
        continue;
      }
      for (const def of definitionBodies(text)) {
        ran = true;
        const missing = rule.required(def.id, def.body).filter((key) => !keys.has(key));
        if (missing.length === 0) continue;
        findings.push({
          code: "new-object-loc",
          rel: file.rel,
          level: "warn",
          message: `semantic: the new ${rule.kind} "${def.id}" has no localization key ${missing
            .map((key) => `"${key}"`)
            .join(" or ")}. Add it under localization/<language>/. The game logs a missing key as an error.`,
        });
      }
    }
  }
  return ran;
}

/** The findings for check 2: a name that is one or two edits away from a game name. */
function checkNearMissNames(
  modDir: string,
  cwd: string,
  dump: DumpNames,
  findings: SemanticFinding[],
): boolean {
  const vanilla = join(cwd, MIRROR_ROOT_DIRNAME, MIRROR_DIRNAME, "game");
  const scriptStat = statSync(join(vanilla, "common"), { throwIfNoEntry: false });
  if (!scriptStat?.isDirectory()) return false;

  const known = new Set<string>(dump.names);
  for (const dir of VANILLA_NAME_DIRS) {
    const files = walkFiles(join(vanilla, dir), (rel) => rel.endsWith(".txt"));
    for (const file of files) {
      let text = "";
      try {
        text = readFileSync(file.abs, "utf8");
      } catch {
        /* An unreadable vanilla file adds no names, and that only risks a false WARN. */
        continue;
      }
      definitionsIn(text, known);
      // Every field that vanilla uses is a legal word too. Vanilla uses fields that no definition
      // list holds (`random_traits`, for example). So the vocabulary of these files is part of the
      // known set. Without it, a correct mod is reported as a misspelling.
      for (const match of scriptOnly(text).matchAll(TOKEN_RE)) known.add(match[0]);
    }
  }

  const reported = new Set<string>();
  const scriptFiles = walkFiles(modDir, (rel) => /\.(txt|gui|gfx|asset)$/i.test(rel));
  for (const file of scriptFiles) {
    let text = "";
    try {
      text = readFileSync(file.abs, "utf8");
    } catch {
      continue;
    }
    const names = new Set<string>();
    definitionsIn(text, names);
    const clean = scriptOnly(text);
    const saved = new Set<string>();
    for (const match of clean.matchAll(SAVED_NAME_RE)) saved.add(match[1]);
    for (const match of clean.matchAll(TOKEN_RE)) {
      const token = match[0];
      if (known.has(token) || names.has(token) || saved.has(token) || reported.has(token)) continue;
      const suggestion = closestName(token, dump, 2);
      if (!suggestion) continue;
      reported.add(token);
      findings.push({
        code: "near-miss-name",
        rel: file.rel,
        level: "warn",
        message: `semantic: "${token}" is not a name that the game's dumps hold. The closest game name is "${suggestion}". Check the spelling, or define it yourself if it is a scripted effect or trigger.`,
      });
      if (findings.length >= MAX_SEMANTIC_FINDINGS) return true;
    }
  }
  return true;
}

/**
 * Run the semantic checks on one mod. `cwd` is the workspace root: the mirror and the dumps are
 * relative to it.
 */
export function analyzeSemantics(modDir: string, cwd: string): SemanticResult {
  const findings: SemanticFinding[] = [];
  const checked: string[] = [];

  if (checkNewObjectLoc(modDir, findings)) {
    checked.push("localization keys for new traits, decisions, and character interactions");
  }

  const dumps = dumpDir(cwd);
  const dump = readDumpNames(dumps);
  if (!dump) {
    findings.push({
      code: "dump-missing",
      rel: "docs/script_docs",
      level: "note",
      message: `semantic: the game's dumps are missing, so the effect, trigger, and modifier names were not checked. Run "node scripts/dump-script-docs.mjs", then validate again.`,
    });
    return { checked, findings };
  }
  if (!checkNearMissNames(modDir, cwd, dump, findings)) {
    findings.push({
      code: "mirror-missing",
      rel: `${MIRROR_ROOT_DIRNAME}/${MIRROR_DIRNAME}`,
      level: "note",
      message: `semantic: the vanilla mirror is missing, so the effect, trigger, and modifier names were not checked: without it, a name that vanilla declares would be reported as unknown. Run sync_game_scripts, then validate again.`,
    });
    return { checked, findings };
  }
  checked.push("effect, trigger, and modifier names against docs/script_docs");

  return { checked, findings };
}
